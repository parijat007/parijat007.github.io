"""Branded images for LinkedIn posts (1080x1350, the portrait size LinkedIn's feed shows largest).

Every word and number on the image comes from the source note: either its `visual:` front-matter block,
written with the note, or (without one) its title, summary and status claims. Nothing is generated by a model,
so the image can't introduce a fact the post's checks didn't see.

  visual:
    kicker: AI Security Spotlight
    title: When the tool tells the agent what to do
    steps:                       # a real sequence only (an attack chain, a timeline); drawn as a numbered flow
      - The agent reads text an attacker can influence
      - ...
    highlight: 4                 # 1-based step drawn in signal red: the moment that matters
    figures:                     # up to three; state is confirmed | reported
      - {value: "22%", label: "of 834 flagged MCP servers", state: reported}
"""
from __future__ import annotations

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FONTS = Path(__file__).resolve().parent.parent / "site" / "og"
W, H = 1080, 1350
M = 84                                                    # outer margin
BASE, PANEL, RULE, CELL = "#0B0F15", "#121823", "#263042", "#364259"
TEXT, MUTED, SIGNAL, TOOLING = "#E8ECF2", "#93A0B4", "#F0283C", "#2BC3B0"
STATE = {"confirmed": (SIGNAL, "Confirmed"), "reported": (TOOLING, "Reported")}
SITE = "theparijat.com"


def _font(kind: str, size: int):
    return ImageFont.truetype(str(FONTS / f"archivo-{kind}.ttf"), size)


def _wrap(d, text: str, font, width: int) -> list[str]:
    lines, cur = [], ""
    for w in str(text).split():
        trial = f"{cur} {w}".strip()
        if d.textlength(trial, font=font) <= width or not cur:
            cur = trial
        else:
            lines.append(cur)
            cur = w
    return lines + ([cur] if cur else [])


def _mark(d, x: int, y: int, size: int) -> None:
    """The Watchfloor mark: a 3x3 floor of tiles, top-right lit red."""
    s = size / 64
    d.rounded_rectangle([x, y, x + size, y + size], radius=int(14 * s), fill=PANEL)
    for r in range(3):
        for c in range(3):
            cx, cy = x + (10 + 16 * c) * s, y + (10 + 16 * r) * s
            d.rounded_rectangle([cx, cy, cx + 12 * s, cy + 12 * s], radius=max(1, int(2.5 * s)),
                                fill=SIGNAL if (r, c) == (0, 2) else CELL)


def _watermark(img: Image.Image) -> Image.Image:
    """A faint diagonal site name across the body: survives cropping and screenshots, never competes with text."""
    layer = Image.new("RGBA", (W * 2, H * 2), (0, 0, 0, 0))
    ld = ImageDraw.Draw(layer)
    f = _font("bold", 46)
    step_x, step_y = int(ld.textlength(SITE, font=f)) + 220, 230
    for row, y in enumerate(range(0, H * 2, step_y)):
        for x in range(-step_x + (row % 2) * step_x // 2, W * 2, step_x):
            ld.text((x, y), SITE, font=f, fill=(232, 236, 242, 5))
    layer = layer.rotate(28, resample=Image.BICUBIC, center=(W, H)).crop((W // 2, H // 2, W // 2 + W, H // 2 + H))
    out = img.convert("RGBA")
    out.alpha_composite(layer)
    return out.convert("RGB")


def render(spec: dict, out: Path) -> Path:
    img = Image.new("RGB", (W, H), BASE)
    img = _watermark(img)
    d = ImageDraw.Draw(img)
    inner = W - 2 * M

    # header: mark, name, kicker
    _mark(d, M, 72, 64)
    d.text((M + 84, 76), "Watchfloor", font=_font("bold", 34), fill=TEXT)
    d.text((M + 84, 116), spec.get("kicker", "Analyst note"), font=_font("regular", 24), fill=MUTED)

    # title
    y = 196
    tf = _font("bold", 64 if len(spec["title"]) < 48 else 54)
    for line in _wrap(d, spec["title"], tf, inner)[:3]:
        d.text((M, y), line, font=tf, fill=TEXT)
        y += int(tf.size * 1.14)
    y += 34

    steps = spec.get("steps") or []
    figures = (spec.get("figures") or [])[:3]
    if spec.get("bars"):
        y = _bars(d, spec["bars"], spec.get("bars_title", ""), y, inner)
    elif steps:
        y = _chain(d, steps, int(spec.get("highlight") or 0), y, inner, bottom=H - (370 if figures else 150))
    elif spec.get("detail"):
        df = _font("regular", 36)
        for line in _wrap(d, spec["detail"], df, inner)[:8]:
            d.text((M, y), line, font=df, fill=MUTED)
            y += 52
    if figures:
        _figures(d, figures, H - 326, inner)

    # footer: rule and the site, the watermark that carries the link
    d.line([M, H - 104, W - M, H - 104], fill=RULE, width=2)
    d.text((M, H - 80), spec.get("footer_left", "Sources and hunting guidance in the full note"),
           font=_font("regular", 24), fill=MUTED)
    d.text((W - M, H - 84), SITE, font=_font("bold", 30), fill=TEXT, anchor="ra")
    out.parent.mkdir(parents=True, exist_ok=True)
    img.save(out, "PNG", optimize=True)
    return out


def _chain(d, steps: list[str], hi: int, y: int, inner: int, bottom: int) -> int:
    """A numbered vertical flow. Numbers are used only because the steps are a sequence."""
    n = len(steps)
    sf, bf = _font("regular", 31), _font("bold", 31)
    wrapped = [_wrap(d, s, bf if i == hi else sf, inner - 96)[:3] for i, s in enumerate(steps, 1)]
    need = sum(len(w) * 40 for w in wrapped) + 30 * (n - 1)
    gap = max(30, min(84, (bottom - y - need) // max(1, n - 1) + 30))
    xs = M + 24
    tops = []
    for i, lines in enumerate(wrapped, 1):
        lit = i == hi
        tops.append(y)
        if lit:   # the moment that matters, in signal red
            d.rounded_rectangle([M - 18, y - 16, W - M + 18, y + len(lines) * 40 + 8], radius=14, fill="#1C1218",
                                outline=SIGNAL, width=2)
        d.ellipse([xs - 24, y - 4, xs + 24, y + 44], fill=SIGNAL if lit else PANEL, outline=SIGNAL if lit else CELL,
                  width=2)
        d.text((xs, y + 20), str(i), font=_font("bold", 26), fill=TEXT, anchor="mm")
        for j, line in enumerate(lines):
            d.text((M + 72, y + 2 + j * 40), line, font=_font("bold", 31) if lit else sf, fill=TEXT if lit else "#C9D1DD")
        y_next = y + len(lines) * 40 + gap
        if i < n:
            d.line([xs, y + 48, xs, y_next - 8], fill=CELL, width=3)
        y = y_next
    return y


def _bars(d, bars: list, title: str, y: int, inner: int) -> int:
    """Horizontal bars for counted data (KEV trends): label, bar, number. Largest bar lit in signal red."""
    if title:
        d.text((M, y), title, font=_font("bold", 30), fill=MUTED)
        y += 58
    top = max(n for _, n in bars) or 1
    lf, nf = _font("regular", 30), _font("bold", 30)
    label_w, bar_x0 = 330, M + 350
    bar_w = inner - 350 - 70
    for i, (label, n) in enumerate(bars[:7]):
        text = label if d.textlength(label, font=lf) <= label_w else _wrap(d, label, lf, label_w - 20)[0] + "…"
        d.text((M, y), text, font=lf, fill=TEXT)
        w = max(6, int(bar_w * n / top))
        d.rounded_rectangle([bar_x0, y + 8, bar_x0 + w, y + 32], radius=4, fill=SIGNAL if i == 0 else CELL)
        d.text((W - M, y + 2), str(n), font=nf, fill=TEXT, anchor="ra")
        y += 64
    return y


def _figures(d, figures: list[dict], y: int, inner: int) -> None:
    n = len(figures)
    gap = 22
    w = (inner - gap * (n - 1)) // n
    for i, f in enumerate(figures):
        x = M + i * (w + gap)
        colour, word = STATE.get(f.get("state", "reported"), STATE["reported"])
        d.rounded_rectangle([x, y, x + w, y + 196], radius=12, fill=PANEL)
        d.rectangle([x, y + 12, x + 6, y + 184], fill=colour)
        d.text((x + 28, y + 18), word, font=_font("bold", 19), fill=colour)
        vf = _font("bold", 52 if len(f["value"]) <= 6 else 40)
        d.text((x + 28, y + 44), f["value"], font=vf, fill=TEXT)
        lf = _font("regular", 21)
        for j, line in enumerate(_wrap(d, f["label"], lf, w - 44)[:3]):
            d.text((x + 28, y + 110 + j * 26), line, font=lf, fill=MUTED)


def spec_from_note(meta: dict) -> dict:
    """The note's own `visual:` block, or a title card from its title and summary."""
    v = dict(meta.get("visual") or {})
    v.setdefault("title", meta["title"])
    if not v.get("steps"):
        v.setdefault("detail", " ".join(str(meta.get("summary", "")).split()))
    return v


def numbers(spec: dict) -> str:
    """All the text drawn on the image, for the judge's fact check."""
    parts = [spec.get("title", ""), spec.get("detail", ""), spec.get("bars_title", ""), *spec.get("steps", []),
             *[f"{label} {n}" for label, n in spec.get("bars", [])]]
    for f in spec.get("figures", []):
        parts += [f["value"], f["label"]]
    return "\n".join(p for p in parts if p)
